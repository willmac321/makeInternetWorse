// Generates puzzles.js: random positions where White has exactly one checkmating move.
// Usage: npm run puzzles -- [count]   (default 295 generated + the classics)
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..", "src");
const ChessEngine = new Function(
  fs.readFileSync(path.join(root, "chess-engine.js"), "utf8") + "\nreturn ChessEngine;"
)();
const { parseFen, toFen, inCheck, matingMoves, allLegalMoves } = ChessEngine;

// Hand-made classics, kept alongside the generated ones.
const CLASSICS = [
  "6k1/5ppp/8/8/8/8/8/R5K1",                              // back rank
  "6rk/6pp/8/6N1/8/8/8/6K1",                              // smothered-ish
  "r1bqkb1r/pppp1ppp/2n2n2/4p2Q/2B1P3/8/PPPP1PPP/RNB1K1NR", // scholar's mate
  "7k/1R6/8/8/8/8/8/R5K1",                                // rook ladder
  "7k/8/6K1/8/8/8/8/1Q6",                                 // queen + king
];

const rand = (n) => Math.floor(Math.random() * n);
const pick = (arr) => arr[rand(arr.length)];

function randomPosition() {
  const board = Array.from({ length: 8 }, () => Array(8).fill(null));
  const empty = () => {
    for (;;) {
      const r = rand(8), c = rand(8);
      if (!board[r][c]) return [r, c];
    }
  };
  // Black king near an edge, where mates happen.
  const kr = Math.random() < 0.7 ? pick([0, 0, 1]) : rand(8);
  const kc = Math.random() < 0.5 ? pick([0, 7, 6, 1]) : rand(8);
  board[kr][kc] = "k";
  // Some black pawns sheltering the king (they also take away escape squares).
  for (const dc of [-1, 0, 1]) {
    const r = kr + 1, c = kc + dc;
    if (r > 0 && r < 7 && c >= 0 && c < 8 && Math.random() < 0.6) board[r][c] = "p";
  }
  const place = (piece) => {
    const [r, c] = empty();
    if (piece.toLowerCase() === "p" && (r === 0 || r === 7)) return;
    board[r][c] = piece;
  };
  place("K");
  const whiteCount = 1 + rand(3);
  for (let i = 0; i < whiteCount; i++) place(pick("QRRBBNNP"));
  const blackCount = rand(4);
  for (let i = 0; i < blackCount; i++) place(pick("rbnqpp"));
  return board;
}

function kingsTouch(board) {
  const find = (k) => {
    for (let r = 0; r < 8; r++) for (let c = 0; c < 8; c++) if (board[r][c] === k) return [r, c];
  };
  const [a, b] = [find("K"), find("k")];
  return !a || !b || (Math.abs(a[0] - b[0]) <= 1 && Math.abs(a[1] - b[1]) <= 1);
}

function isGoodPuzzle(board) {
  if (kingsTouch(board) || inCheck(board, "b") || inCheck(board, "w")) return false;
  // Black must have had a legal last move, roughly: at least one legal black move exists.
  if (allLegalMoves(board, "b").length === 0) return false;
  // Exactly one mate, and enough legal white moves that it isn't obvious.
  return matingMoves(board, "w").length === 1 && allLegalMoves(board, "w").length >= 8;
}

const count = Number(process.argv[2] || 295);
const fens = new Set();
for (const fen of CLASSICS) {
  const mates = matingMoves(parseFen(fen), "w");
  if (mates.length === 0) throw new Error(`classic has no mate: ${fen}`);
  fens.add(fen);
}
let tries = 0;
while (fens.size < CLASSICS.length + count) {
  tries++;
  const board = randomPosition();
  if (isGoodPuzzle(board)) fens.add(toFen(board));
}

const out =
  "// Mate-in-one puzzles, White to move. Generated by tools/generate-puzzles.js.\n" +
  "// The winning move(s) are worked out at runtime by ChessEngine.matingMoves.\n" +
  "const PUZZLES = [\n" + [...fens].map((f) => `  "${f}",`).join("\n") + "\n];\n";
fs.writeFileSync(path.join(root, "puzzles.js"), out);
console.log(`wrote ${fens.size} puzzles (${tries} random tries)`);
